/* Project page: interactive figures (custom SVG, no dependencies).
   Data: static/data/benchmarks.js (generated by scripts/build_data.py). */
(function () {
  "use strict";

  var el = window.BF.el, $ = window.BF.$, $$ = window.BF.$$;
  var DOMAINS = ["Math", "Coding", "Agentic Tasks", "Science", "Instruction Following", "Logic", "Medicine"];
  var COLORS = { ink: "#1d1d1f", ref: "#8a8f96", area: "rgba(36,87,197,0.13)", gap: "rgba(63,143,79,0.14)",
    gapStrong: "rgba(63,143,79,0.24)", gapLine: "#3f8f4f", tick: "#6b7f99", accent: "#2457c5", base: "#c9741f" };

  function fmt(v, d) { return v.toFixed(d == null ? 3 : d); }
  function clear(node) { while (node.firstChild) node.removeChild(node.firstChild); }

  /** Adjacent gaps of sorted difficulties in [0,1], including the endpoint gaps at 0 and 1. */
  function gapsOf(sorted) {
    var pts = [0].concat(sorted, [1]), out = [];
    for (var i = 0; i < pts.length - 1; i++) out.push({ lo: pts[i], hi: pts[i + 1], w: pts[i + 1] - pts[i] });
    return out;
  }
  function topGaps(sorted, k) {
    return gapsOf(sorted).map(function (g, i) { g.i = i; return g; })
      .sort(function (a, b) { return b.w - a.w || a.i - b.i; }).slice(0, k)
      .map(function (g, r) { g.rank = r + 1; return g; });
  }
  /** DDM as computed in the paper: W1 to the same-size uniform reference at bin midpoints. */
  function ddmOf(sorted) {
    var n = sorted.length, s = 0;
    for (var i = 0; i < n; i++) s += Math.abs(sorted[i] - (i + 0.5) / n);
    return s / n;
  }
  function ecdfAt(sorted, x) {
    var lo = 0, hi = sorted.length;
    while (lo < hi) { var m = (lo + hi) >> 1; if (sorted[m] <= x) lo = m + 1; else hi = m; }
    return lo / sorted.length;
  }
  function stepPath(sorted, sx, sy) {
    var n = sorted.length, d = "M" + sx(0) + "," + sy(0);
    for (var i = 0; i < n; i++) d += "H" + sx(sorted[i]).toFixed(2) + "V" + sy((i + 1) / n).toFixed(2);
    return d + "H" + sx(1);
  }

  function placeTip(tip, box, px, py) {
    tip.hidden = false;
    var bw = box.clientWidth, tw = tip.offsetWidth, th = tip.offsetHeight;
    var left = px + 14;
    if (left + tw > bw) left = px - tw - 14;
    if (left < 0) left = Math.max(0, Math.min(bw - tw, px - tw / 2));
    var top = py - th - 12;
    if (top < 0) top = py + 16;
    tip.style.left = left + "px";
    tip.style.top = top + "px";
  }

  function observeWidth(node, fn) {
    var last = 0;
    var run = function () { var w = node.clientWidth; if (w && Math.abs(w - last) > 2) { last = w; fn(w); } };
    if ("ResizeObserver" in window) new ResizeObserver(run).observe(node);
    else window.addEventListener("resize", run);
    run();
  }

  /* =====================================================================
     1. ECDF explorer
     ===================================================================== */
  function initExplorer() {
    var data = window.BENCHMARKS;
    var app = $("#explorer-app");
    if (!app || !data) return;
    var select = $("#ex-select"), svg = $("#ex-chart"), tip = $("#ex-tip"), box = svg.parentNode;
    var tiles = $("#ex-metrics"), note = $("#ex-note");
    var optArea = $("#ex-area"), optGaps = $("#ex-gaps"), optRug = $("#ex-rug");
    var byName = {};
    data.forEach(function (b) {
      byName[b.name] = b;
      if (b.items) {
        // Cross-check the bundled items against the paper's Table 1 values.
        var dd = ddmOf(b.items), tg = topGaps(b.items, 5);
        var mg = tg[0].w, t5 = tg.reduce(function (a, g) { return a + g.w; }, 0);
        if (Math.abs(dd - b.ddm) > 0.0011 || Math.abs(mg - b.maxGap) > 0.0011 || Math.abs(t5 - b.top5) > 0.0011 || b.items.length !== b.n) {
          console.warn("Explorer data for " + b.name + " does not match Table 1", dd, mg, t5);
        }
      }
    });

    DOMAINS.forEach(function (dom) {
      var og = document.createElement("optgroup");
      og.label = dom;
      data.filter(function (b) { return b.domain === dom && b.items; }).forEach(function (b) {
        var o = document.createElement("option");
        o.value = b.name;
        o.textContent = b.name;
        og.appendChild(o);
      });
      select.appendChild(og);
    });
    select.value = "AIME24";

    var width = 760;

    function renderTiles(b) {
      var t = [
        ["DDM", fmt(b.ddm), b.ddm >= 0.10, "≥ 0.10"],
        ["Max Gap", fmt(b.maxGap), b.maxGap >= 0.10, "≥ 0.10"],
        ["Top-5 Gap Sum", fmt(b.top5), b.top5 >= 0.30, "≥ 0.30"],
        ["Items", String(b.n), false, ""]
      ];
      tiles.innerHTML = t.map(function (x) {
        return '<div class="mtile' + (x[2] ? " high" : "") + '"><p class="k">' + x[0] + '</p><p class="v">' + x[1] + "</p>" +
          '<p class="flag">' + (x[2] ? "large (" + x[3] + ")" : (x[0] === "Items" ? b.domain : "&nbsp;")) + "</p></div>";
      }).join("");
    }

    function draw() {
      var b = byName[select.value];
      renderTiles(b);
      $$("#table1 tr.clickable").forEach(function (tr) { tr.classList.toggle("selected", tr.dataset.name === b.name); });
      tip.hidden = true;

      note.textContent = "Hover or tap the chart to read values.";

      var z = b.items, n = z.length;
      var W = width, compact = W < 520;
      var H = Math.round(Math.max(270, Math.min(430, W * 0.56)));
      var m = { l: compact ? 40 : 52, r: 14, t: 34, b: 62 };
      var pw = W - m.l - m.r, ph = H - m.t - m.b;
      var sx = function (v) { return m.l + v * pw; };
      var sy = function (v) { return m.t + (1 - v) * ph; };
      svg.setAttribute("viewBox", "0 0 " + W + " " + H);
      svg.setAttribute("width", W);
      svg.setAttribute("height", H);
      clear(svg);
      el("title", {}, svg, "ECDF of normalized item difficulty for " + b.name);

      var grid = el("g", { class: "grid" }, svg);
      [0, 0.2, 0.4, 0.6, 0.8, 1].forEach(function (v) {
        el("line", { x1: m.l, x2: m.l + pw, y1: sy(v), y2: sy(v) }, grid);
        el("line", { y1: m.t, y2: m.t + ph, x1: sx(v), x2: sx(v) }, grid);
      });

      var uni = [];
      for (var i = 0; i < n; i++) uni.push((i + 0.5) / n);
      var gaps = topGaps(z, 5);

      if (optGaps.checked) {
        var gl = el("g", {}, svg);
        var labels = [];
        gaps.slice().sort(function (a, c) { return a.lo - c.lo; }).forEach(function (g) {
          if (g.w <= 0) return;
          el("rect", { x: sx(g.lo), y: m.t, width: Math.max(1, sx(g.hi) - sx(g.lo)), height: ph, fill: g.rank === 1 ? COLORS.gapStrong : COLORS.gap }, gl);
          el("line", { x1: sx(g.lo), x2: sx(g.lo), y1: m.t, y2: m.t + ph, stroke: COLORS.gapLine, "stroke-opacity": 0.35, "stroke-dasharray": "3 3" }, gl);
          el("line", { x1: sx(g.hi), x2: sx(g.hi), y1: m.t, y2: m.t + ph, stroke: COLORS.gapLine, "stroke-opacity": 0.35, "stroke-dasharray": "3 3" }, gl);
          labels.push({ x: (sx(g.lo) + sx(g.hi)) / 2, g: g });
        });
        // Two label rows to avoid collisions between neighbouring narrow gaps.
        var lastX = [-1e9, -1e9];
        labels.forEach(function (L) {
          var row = (L.x - lastX[0] > 34) ? 0 : (L.x - lastX[1] > 34 ? 1 : 0);
          lastX[row] = L.x;
          var y = m.t - 8 - row * 13;
          el("text", { x: L.x, y: y, "text-anchor": "middle", "font-size": 10.5, fill: "#2f6f3c", "font-weight": L.g.rank === 1 ? 700 : 500 }, gl, fmt(L.g.w, 2));
        });
      }

      if (optArea.checked) {
        // Area between the two step functions; equals DDM exactly.
        var xs = [0].concat(z, uni, [1]).sort(function (a, c) { return a - c; });
        var d = "";
        for (var k = 0; k < xs.length - 1; k++) {
          var x0 = xs[k], x1 = xs[k + 1];
          if (x1 - x0 <= 0) continue;
          var F = ecdfAt(z, x0), G = ecdfAt(uni, x0);
          if (F === G) continue;
          d += "M" + sx(x0).toFixed(2) + "," + sy(F).toFixed(2) + "H" + sx(x1).toFixed(2) + "V" + sy(G).toFixed(2) + "H" + sx(x0).toFixed(2) + "Z";
        }
        el("path", { d: d, fill: COLORS.area, stroke: "none" }, svg);
      }

      el("path", { d: stepPath(uni, sx, sy), fill: "none", stroke: COLORS.ref, "stroke-width": 1.6, "stroke-dasharray": "5 4" }, svg);
      el("path", { d: stepPath(z, sx, sy), fill: "none", stroke: COLORS.ink, "stroke-width": 2, "stroke-linejoin": "round" }, svg);

      // frame + axes
      var ax = el("g", { class: "ax" }, svg);
      el("line", { x1: m.l, x2: m.l + pw, y1: m.t + ph, y2: m.t + ph }, ax);
      el("line", { x1: m.l, x2: m.l, y1: m.t, y2: m.t + ph }, ax);
      var rugY = m.t + ph + 4;
      [0, 0.2, 0.4, 0.6, 0.8, 1].forEach(function (v) {
        el("text", { x: sx(v), y: m.t + ph + 30, "text-anchor": "middle" }, ax, v.toFixed(1));
        el("text", { x: m.l - 7, y: sy(v) + 4, "text-anchor": "end" }, ax, v.toFixed(1));
      });
      el("text", { class: "ax-title", x: m.l + pw / 2, y: H - 8, "text-anchor": "middle" }, svg, "Normalized Item Difficulty");
      el("text", { class: "ax-title", x: 12, y: m.t + ph / 2, "text-anchor": "middle", transform: "rotate(-90 12 " + (m.t + ph / 2) + ")" }, svg, "ECDF");

      if (optRug.checked) {
        var rd = "";
        z.forEach(function (v) { rd += "M" + sx(v).toFixed(2) + "," + rugY + "v9"; });
        el("path", { d: rd, stroke: COLORS.tick, "stroke-opacity": n > 400 ? 0.35 : 0.7, "stroke-width": 1 }, svg);
      }

      // hover layer
      var cross = el("line", { y1: m.t, y2: m.t + ph, stroke: "#5f6368", "stroke-width": 1, visibility: "hidden" }, svg);
      var dotF = el("circle", { r: 4.5, fill: COLORS.ink, stroke: "#fff", "stroke-width": 2, visibility: "hidden" }, svg);
      var dotG = el("circle", { r: 4, fill: COLORS.ref, stroke: "#fff", "stroke-width": 2, visibility: "hidden" }, svg);
      var hit = el("rect", { x: m.l, y: m.t - 30, width: pw, height: ph + 48, fill: "transparent", style: "cursor:crosshair" }, svg);
      function move(ev) {
        var r = svg.getBoundingClientRect();
        var px = (ev.clientX - r.left) * (W / r.width);
        var x = Math.max(0, Math.min(1, (px - m.l) / pw));
        var F = ecdfAt(z, x), G = ecdfAt(uni, x);
        [cross, dotF, dotG].forEach(function (e) { e.setAttribute("visibility", "visible"); });
        cross.setAttribute("x1", sx(x)); cross.setAttribute("x2", sx(x));
        dotF.setAttribute("cx", sx(x)); dotF.setAttribute("cy", sy(F));
        dotG.setAttribute("cx", sx(x)); dotG.setAttribute("cy", sy(G));
        var inGap = null;
        gaps.forEach(function (g) { if (x >= g.lo && x <= g.hi && g.w > 0) inGap = g; });
        var html = '<span class="tt-k">normalized item difficulty</span> <b>' + fmt(x, 3) + '</b><br><span class="tt-k">benchmark ECDF</span> <b>' + fmt(F, 3) +
          '</b><br><span class="tt-k">uniform reference</span> <b>' + fmt(G, 3) + "</b>";
        if (inGap) html += '<br><span style="color:#2f6f3c">gap #' + inGap.rank + ": [" + fmt(inGap.lo) + ", " + fmt(inGap.hi) + "], width <b>" + fmt(inGap.w) + "</b></span>";
        tip.innerHTML = html;
        var bx = box.getBoundingClientRect();
        placeTip(tip, box, ev.clientX - bx.left, (sy(F) / H) * r.height + (r.top - bx.top));
      }
      function leave() { tip.hidden = true; [cross, dotF, dotG].forEach(function (e) { e.setAttribute("visibility", "hidden"); }); }
      hit.addEventListener("pointermove", move);
      hit.addEventListener("pointerdown", move);
      hit.addEventListener("pointerleave", leave);
    }

    select.addEventListener("change", draw);
    [optArea, optGaps, optRug].forEach(function (c) { c.addEventListener("change", draw); });
    observeWidth(box, function (w) { width = w; draw(); });

    function openInExplorer(name) {
      if (!byName[name] || !byName[name].items) return;
      select.value = name;
      draw();
      document.getElementById("explorer").scrollIntoView({ behavior: window.matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth" });
    }
    $$("#table1 tr.clickable").forEach(function (tr) {
      tr.addEventListener("click", function () { openInExplorer(tr.dataset.name); });
      tr.addEventListener("keydown", function (e) { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); openInExplorer(tr.dataset.name); } });
    });
  }

  initExplorer();
})();
