"""Build the static data file used by the website's benchmark explorer.

Reads the Difficulty Artifact of the official code release
(data/benchmarks/<benchmark>/difficulty.csv, unnormalized IRT b_mean) and writes

  static/data/benchmarks.js  - Table 1 metrics for all 25 benchmarks, plus normalized
                               item difficulties for benchmarks whose released estimates
                               reproduce Table 1.

The paper is the source of truth for every displayed metric. This script recomputes
the metrics from the released difficulties and refuses to bundle item-level data
for a benchmark unless it matches the paper's Table 1 within 0.001.

Usage:
    python scripts/build_data.py PATH/TO/benchfill-release static/data
"""
